-- Поход: PostgreSQL schema, validation and row-level security.
-- Run in a new Supabase project. No service-role key is used by the client.
begin;
create schema if not exists private;
create schema if not exists extensions;
create extension if not exists btree_gist with schema extensions;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create table public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null,
 role text not null default 'client' check (role in ('client','employee','admin')),
 created_at timestamptz not null default now()
);
create table public.categories (
 id bigint generated by default as identity primary key,
 name text not null, description text not null default '',
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create unique index categories_name_key on public.categories(lower(name));
create table public.brands (
 id bigint generated by default as identity primary key,
 name text not null, country text not null,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create unique index brands_name_key on public.brands(lower(name));
create table public.locations (
 id bigint generated by default as identity primary key,
 name text not null, address text not null, phone text not null,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create unique index locations_name_key on public.locations(lower(name));
create table public.equipment (
 id bigint generated by default as identity primary key,
 name text not null, sku text not null,
 category_id bigint not null references public.categories(id), brand_id bigint not null references public.brands(id),
 daily_rate integer not null check(daily_rate between 1 and 50000),
 deposit integer not null default 0 check(deposit between 0 and 300000),
 weight_grams integer not null default 0 check(weight_grams between 0 and 500000), description text not null default '',
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create unique index equipment_sku_key on public.equipment(lower(sku));
create table public.units (
 id bigint generated by default as identity primary key,
 inventory_code text not null,
 equipment_id bigint not null references public.equipment(id), location_id bigint not null references public.locations(id),
 state text not null default 'ready' check(state in ('ready','maintenance','retired')),
 acquired_on date not null default current_date, note text not null default '',
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create unique index units_inventory_code_key on public.units(lower(inventory_code));
create table public.customers (
 id bigint generated by default as identity primary key,
 user_id uuid unique references auth.users(id) on delete set null,
 full_name text not null, email text not null, phone text not null,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create unique index customers_email_key on public.customers(lower(email));
create table public.loyalty_cards (
 id bigint generated by default as identity primary key,
 customer_id bigint not null unique references public.customers(id) on delete cascade,
 number text not null unique,
 discount_percent integer not null default 0 check(discount_percent between 0 and 10),
 issued_on date not null default current_date, expires_on date not null default (current_date+365),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz,
 check(expires_on>issued_on)
);
create table public.services (
 id bigint generated by default as identity primary key,
 name text not null, price integer not null check(price between 0 and 50000), description text not null default '',
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create unique index services_name_key on public.services(lower(name));
create table public.rentals (
 id bigint generated by default as identity primary key,
 customer_id bigint not null references public.customers(id), location_id bigint not null references public.locations(id),
 start_on date not null, end_on date not null,
 status text not null default 'reserved' check(status in ('reserved','issued','returned','cancelled')),
 notes text not null default '',
 base_cost numeric(12,2) not null default 0,
 discount_percent integer not null default 0,
 services_cost numeric(12,2) not null default 0,
 total_cost numeric(12,2) not null default 0,
 deposit numeric(12,2) not null default 0,
 late_fee numeric(12,2) not null default 0,
 issued_at timestamptz, returned_at timestamptz,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz,
 check(end_on>start_on and end_on-start_on<=90)
);
create table public.rental_items (
 id bigint generated by default as identity primary key,
 rental_id bigint not null references public.rentals(id) on delete cascade,
 unit_id bigint not null references public.units(id),
 equipment_name text not null, inventory_code text not null,
 daily_rate integer not null, deposit integer not null,
 booked_period daterange not null,
 active boolean not null default true,
 unique(rental_id,unit_id),
 exclude using gist(unit_id with =, booked_period with &&) where(active)
);
create table public.rental_services (
 rental_id bigint not null references public.rentals(id) on delete cascade,
 service_id bigint not null references public.services(id),
 service_name text not null, price integer not null,
 primary key(rental_id,service_id)
);
create index rentals_customer_dates_idx on public.rentals(customer_id,start_on,end_on);
create index rentals_status_idx on public.rentals(status) where deleted_at is null;
create index units_location_equipment_idx on public.units(location_id,equipment_id);
create index equipment_category_brand_idx on public.equipment(category_id,brand_id);

create or replace function private.fail(p_status integer,p_message text,p_fields jsonb default '{}'::jsonb)
returns void language plpgsql set search_path='' as $$
begin
 raise sqlstate 'PGRST' using message=jsonb_build_object('code','TR'||p_status,'message',p_message,'details',p_fields::text,'hint',null)::text,
 detail=jsonb_build_object('status',p_status)::text;
end $$;
create or replace function private.actor_role() returns text language sql stable security definer set search_path='' as $$
 select coalesce((select role from public.profiles where id=(select auth.uid())), '');
$$;
create or replace function private.customer_id() returns bigint language sql stable security definer set search_path='' as $$
 select id from public.customers where user_id=(select auth.uid()) and deleted_at is null;
$$;
grant execute on function private.actor_role(), private.customer_id() to authenticated;

