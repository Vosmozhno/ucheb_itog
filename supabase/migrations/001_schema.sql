-- Customers can edit contacts only via a narrowly scoped RPC.

create or replace function public.update_my_contacts(p_full_name text,p_phone text,p_email text) returns public.customers
language plpgsql security definer set search_path='' as $$
declare c public.customers;
begin
 if private.actor_role()<>'client' then perform private.fail(403,'Личный профиль доступен только клиенту'); end if;
 update public.customers set full_name=p_full_name,phone=p_phone,email=p_email where id=private.customer_id() returning * into c;
 if not found then perform private.fail(404,'Клиент не найден'); end if;
 update public.profiles set full_name=c.full_name where id=auth.uid();
 return c;
end $$;

create or replace function public.register_profile() returns trigger language plpgsql security definer set search_path='' as $$
declare customer bigint; person text;
begin
 person:=left(coalesce(nullif(btrim(new.raw_user_meta_data->>'full_name'),''),split_part(new.email,'@',1),'Новый клиент'),100);
 if length(person)<2 then person:='Клиент '||person; end if;
 insert into public.profiles(id,full_name) values(new.id,person);
 insert into public.customers(user_id,full_name,email,phone) values(new.id,person,new.email,coalesce(nullif(new.raw_user_meta_data->>'phone',''),'+70000000000')) returning id into customer;
 insert into public.loyalty_cards(customer_id,number) values(customer,'TR-'||lpad(customer::text,6,'0'));
 return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.register_profile();

